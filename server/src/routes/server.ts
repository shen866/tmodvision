import { Router, Request } from 'express';
import {
  getStatus,
  checkPublishedPort,
  prepareServerImage,
  operation,
  startServer,
  stopServer,
  restartServer,
} from '../services/docker';
import { getOnlinePlayers, monitor } from '../services/players';
import { deleteServer } from '../services/create';

import { launchSettings, readLaunch, changedKeys } from '../services/launch';
import { getServerById, listServers, saveServers, editRegistry, checkPort } from '../servers';
import { defaultVersion, checkVersion } from '../services/releases';
import fs from 'fs/promises';
import path from 'path';

const router = Router({ mergeParams: true });

function gamePhase(
  status: Awaited<ReturnType<typeof getStatus>>,
  metrics: ReturnType<typeof monitor>
) {
  if (status.state === 'restarting') return '容器重启中';
  if (!status.running) return status.exitCode ? '异常退出' : '已停止';
  if (metrics.ready) return '可加入';
  if (metrics.ready === null) return metrics.sampledAt ? '状态未知' : '等待监控采样';
  if (metrics.gameError) return '启动异常';
  return metrics.stage || '等待游戏就绪';
}

router.get('/status', async (req: Request<{ serverId: string }>, res, next) => {
  try {
    const { serverId } = req.params;
    const status = await getStatus(serverId);
    const server = await getServerById(serverId);
    const desired = await launchSettings(serverId);
    const applied = await readLaunch(serverId, status.startedAt);
    const metrics = monitor(serverId, status.running ? status.startedAt : undefined);
    const job = operation(serverId);
    const pending = [
      ...(server.version && server.version !== status.version ? ['版本 → ' + server.version] : []),
      ...(status.hostPort && status.hostPort !== server.port ? ['端口 → ' + server.port] : []),
      ...(applied
        ? changedKeys(applied.mods, desired.mods).map(
            (name) =>
              (name in desired.mods
                ? name in applied.mods
                  ? '更新模组 · '
                  : '启用模组 · '
                : '禁用模组 · ') + name
          )
        : []),
      ...(applied ? changedKeys(applied.config, desired.config).map((key) => '配置 · ' + key) : []),
    ];
    res.json({
      ...status,
      ...job,
      ...metrics,
      lastError: job.lastError || (!metrics.ready && metrics.gameError) || undefined,
      pending,
      appliedKnown: !!applied,
      phase: job.activity || gamePhase(status, metrics),
      port: server.port,
      maxplayers: applied?.maxplayers ?? null,
      world: applied?.world,
      plannedWorld: desired.world,
      appliedMods: applied ? Object.keys(applied.mods) : null,
      activeVersion: status.version,
      plannedVersion: server.version || status.version || defaultVersion,
    });
  } catch (err) {
    next(err);
  }
});

router.post('/plan', async (req: Request<{ serverId: string }>, res, next) => {
  try {
    await editRegistry(async () => {
      const id = req.params.serverId;
      const server = await getServerById(id);
      const servers = await listServers();
      const port = Number(req.body.port ?? server.port);
      checkPort(servers, id, port);
      await checkPublishedPort(port, server.containerName);
      const updated = {
        ...server,
        port,
        version: req.body.version === undefined ? server.version : checkVersion(req.body.version),
      };
      const compose = path.join(server.composeDir, 'docker-compose.yml');
      // Only update compose files generated by this panel.
      const old = await fs.readFile(compose, 'utf8').catch(() => '');
      if (
        old.includes('container_name: ' + server.containerName) &&
        old.includes('TMOD_AUTODOWNLOAD=')
      ) {
        const content = old
          .replace(/- TMOD_VERSION=.*/, '- TMOD_VERSION=' + (updated.version || defaultVersion))
          .replace('"' + server.port + ':7777"', '"' + updated.port + ':7777"');
        await fs.writeFile(compose + '.tmp', content);
        await fs.rename(compose + '.tmp', compose);
      }
      await saveServers(servers.map((s) => (s.id === id ? updated : s)));
    });
    res.json({ success: true });
  } catch (err) {
    next(err);
  }
});

